import time
import requests


def get_kline(
    symbol: str,
    interval: str = "60",
    category: str = "linear",
    start: int | None = None,
    end: int | None = None,
    limit: int = 200,
    # base_url: str = "https://api-demo.bybit.com",
    base_url: str = "http://127.0.0.1:8000",
) -> dict:
    """
    Запрашивает исторические свечи (Kline) с Bybit V5.

    :param symbol:    Торговая пара, например "BTCUSDT"
    :param interval:  Интервал: 1,3,5,15,30,60,120,240,360,720,D,W,M
    :param category:  Тип продукта: spot / linear / inverse
    :param start:     Начало диапазона (timestamp в мс). Необязательно.
    :param end:       Конец диапазона (timestamp в мс). Необязательно.
    :param limit:     Кол-во свечей [1, 1000]. По умолчанию 200.
    :param base_url:  Базовый URL (демо: https://api-demo.bybit.com)
    :return: JSON-ответ от Bybit в виде словаря
    """
    # Параметры GET-запроса (публичный, без подписи)
    params: dict = {
        "category": category,
        "symbol": symbol,
        "interval": interval,
        "limit": limit,
    }
    if start is not None:
        params["start"] = start
    if end is not None:
        params["end"] = end

    # GET-запрос: параметры идут в URL, подпись не нужна
    response = requests.get(
        base_url + "/v5/market/kline",
        params=params,
        timeout=10,
    )
    response.raise_for_status()
    return response.json()


def print_kline(result: dict) -> None:
    """Печатает свечи в читаемом виде."""
    if result.get("retCode") != 0:
        print(f"❌ Ошибка: {result.get('retMsg')}")
        return

    klines = result.get("result", {}).get("list", [])
    if not klines:
        print("Нет данных")
        return

    # Bybit возвращает свечи в обратном порядке (сначала новые)
    # Разворачиваем, чтобы шли хронологически
    klines = list(reversed(klines))

    print(f"\n✅ Свечей: {len(klines)}")
    for k in klines:
        # Формат: [startTime, open, high, low, close, volume, turnover]
        start_ms = int(k[0])
        dt = time.strftime("%Y-%m-%d %H:%M:%S", time.gmtime(start_ms / 1000))
        print(
            f"   {dt} UTC | "
            f"O={k[1]:>10} H={k[2]:>10} L={k[3]:>10} C={k[4]:>10} | "
            f"V={k[5]:>15}"
        )


